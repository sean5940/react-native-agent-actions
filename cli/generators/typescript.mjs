// @ts-check
import { pascalCase } from '../schema.mjs';

/**
 * @typedef {import('../schema.mjs').Schema} Schema
 * @typedef {import('../schema.mjs').Action} Action
 * @typedef {import('../schema.mjs').Param} Param
 * @typedef {import('../schema.mjs').Value} Value
 */

/**
 * @param {string} text
 * @param {string} indent
 */
function doc(text, indent) {
  const safe = text.replace(/\*\//g, '*\\/');
  const lines = safe.split('\n');
  if (lines.length === 1) {
    return [`${indent}/** ${lines[0]} */`];
  }
  return [`${indent}/**`, ...lines.map((line) => `${indent} * ${line}`), `${indent} */`];
}

/**
 * @param {Value} value
 * @returns {string}
 */
function valueType(value) {
  if (value.kind === 'primitive') {
    return { string: 'string', number: 'number', integer: 'number', boolean: 'boolean' }[value.type];
  }
  if (value.kind === 'object') {
    return value.name;
  }
  const item = valueType(value.items);
  return `${item}[]`;
}

/** @param {Extract<Value, { kind: 'object' }>} object */
function objectInterface(object) {
  const lines = object.description ? doc(object.description, '') : [];
  lines.push(`export interface ${object.name} {`);
  for (const property of object.properties) {
    if (property.value.description) {
      lines.push(...doc(property.value.description, '  '));
    }
    const type = valueType(property.value);
    lines.push(property.value.optional ? `  ${property.name}?: ${type} | null;` : `  ${property.name}: ${type};`);
  }
  lines.push('}');
  return lines.join('\n');
}

/** @param {Action} action */
function paramsInterface(action) {
  const lines = [`export interface ${pascalCase(action.name)}Params {`];
  for (const param of action.params) {
    lines.push(...doc(param.description, '  '));
    const type = { string: 'string', number: 'number', integer: 'number', boolean: 'boolean', stringArray: 'string[]' }[param.type];
    lines.push(param.optional ? `  ${param.name}?: ${type};` : `  ${param.name}: ${type};`);
  }
  lines.push('}');
  return lines.join('\n');
}

/**
 * @param {Schema} schema
 * @returns {string}
 */
export function generateTypeScript(schema) {
  const objects = [...schema.objects.values()];
  const sections = [
    '// Generated by react-native-agent-actions. Do not edit.',
    '// Change agent-actions.config and run `npx react-native-agent-actions generate`.',
    '',
    "import type { AgentActionResult } from 'react-native-agent-actions';",
    '',
  ];
  for (const object of objects) {
    sections.push(objectInterface(object), '');
  }
  for (const action of schema.actions) {
    if (action.params.length > 0) {
      sections.push(paramsInterface(action), '');
    }
  }

  sections.push('/** Pass this type to `registerAgentActions` so every declared action gets a handler with the right types. */');
  sections.push('export interface AgentActionHandlers {');
  for (const action of schema.actions) {
    const params = action.params.length > 0 ? `${pascalCase(action.name)}Params` : 'Record<string, never>';
    const result = action.result ? valueType(action.result) : 'void';
    sections.push(...doc(action.description, '  '));
    sections.push(`  ${action.name}(params: ${params}): AgentActionResult<${result}>;`);
  }
  sections.push('}');
  sections.push('');
  return sections.join('\n');
}
